/**
 * 节气 → 季内**秩次**（0..1），六档等距。
 *
 * ★★★ 为什么必须用秩次而不是 warmth 线性归一化（2026-10-04 实测）：
 *   线性归一化后各档的**步长极不均匀**，实测相邻步长比高达 **40~60 倍**。
 *   根因：`warmth` 是「气温」，而**物候与气温并不同步**（夏至之后还热、小暑反而更热）。
 *   正解：季内按**物候顺序**取秩次，六档固定占 0/.2/.4/.6/.8/1.0 ⇒ **步长恒定**。
 *
 * ⚠️ 这张表是**物候序**（季内真实顺序），不能从 `SOLAR_TERMS` filter 出来：
 *   24 序是**历法序、跨年排布**，filter 出来是「谷雨→立夏」这种跨季拼接，
 *   会让季内断言全部误判。下方 SEG 的段序则必须用历法序 —— **两个序各司其职**。
 */
const TERM_RANK = {
  spring: ['立春', '雨水', '惊蛰', '春分', '清明', '谷雨'],
  summer: ['立夏', '小满', '芒种', '夏至', '小暑', '大暑'],
  autumn: ['立秋', '处暑', '白露', '秋分', '寒露', '霜降'],
  winter: ['立冬', '小雪', '大雪', '冬至', '小寒', '大寒'],
};
/** warmth 的季内 min/max（实测 24 档真值）—— **只用于没有节气名时的线性兜底**。
 *  ⚠️ 若改了 almanac.js 的 warmth 须复核这张表；正常路径走 RANK，不依赖它。 */
const SEASON_WARMTH = { spring: [.30, .68], summer: [.74, .99], autumn: [.38, .80], winter: [.02, .28] };

/**
 * 秩次 0/.2/.4/.6/.8/1.0（每季六档）。
 * ⚠️ 跨年排布：夏天的第 6 档（大暑）之后接的是**下一季的第 1 档**（立秋，秩次 0）。
 */
const RANK = (() => {
  const m = new Map();
  for (const list of Object.values(TERM_RANK)) list.forEach((t, k) => m.set(t, k / (list.length - 1)));
  return m;
})();

/**
 * 段内连续插值表：`SEG.get(term)` = 从这一档走到**日历上的下一档**时，warmth 与 rank 的两端。
 *
 * ★★★ 为什么必须有这张表（2026-10-04，`probe-terms.mjs` ⑨ 段抓到的真缺陷）：
 *   真实运行路径是 `blendTerm(almanac.term, t)` —— **`almanac.term` 恒为离散的
 *   "from 档"，而 `t` 是这一档之内已走过的比例（0→1，约 15 天）**。
 *   第一版 `seasonalWarmth()` 只看 `RANK.get(term)`，等于把整个 15 天压成同一个值：
 *   水色在**交节那一帧跳一下，然后 15 天不动** —— 是阶梯函数，不是渐变。
 *   这直接违反本模块铁律③（连续优先于精确），而且旧探针会假绿：
 *   只在 t=0 取样的话，24 档全对，看不出 t 的问题。
 *
 *   正解：段内用 warmth **反解**出 t，再线性插值 rank。
 *   · t=0 时 warmth 恰为 w0 ⇒ rank 精确等于 r0 ⇒ **24 档的秩次一步不变**，
 *     季内步长仍然恒定 0.050（这是本方案的全部收益，不能丢）；
 *   · 0<t<1 时 rank 落在 r0..r1 之间 ⇒ tint 严格落在两端之间，插值断言成立；
 *   · 顺带修好**跨季那一帧的硬跳**：谷雨(r=1)→立夏(r=0) 现在是 15 天的连续过渡，
 *     而不是"啪"地一下从黄绿跳到青蓝 —— 这正好是用户投诉的"季节切换太明显"。
 *
 * ⚠️⚠️ 必须按 **SOLAR_TERMS 的日历序**建，不能按 TERM_RANK 的分组顺序。
 *   第一版按季节分组 + `(i+1)%n` 绕回，谷雨那一段因此指向了「立春」——
 *   **日历上谷雨之后是立夏，中间隔着整个夏天**。后果：谷雨/霜降/大寒三段
 *   全用错了 warmth 区间（探针立刻报「全段恒定」与「步长不均」）。
 *   教训：**"季内相邻"和"日历相邻"是两个不同的序**，
 *   秩次表可以按季分组（只管组内等距），但**段**必须按日历序连。
 *
 * ⚠️ warmth 在季内**并非单调**（夏至 .99 → 小暑 .93），但这不构成问题：
 *   反解用的是"这一段自己的两端"，w0/w1 谁大谁小都成立（除法带符号）。
 *   唯一要求是 w0 ≠ w1，而 24 档 warmth 两两不等（实测 .02~.99 共 24 个不同值）。
 */
const SEG = new Map(SOLAR_TERMS.map((term, i) => {
  const next = SOLAR_TERMS[(i + 1) % SOLAR_TERMS.length];
  return [term, {
    w0: termProfile(term).warmth,
    r0: RANK.get(term),
    w1: termProfile(next).warmth,
    // ★ 跨季时 r1 是**下一季的第 1 档 = 0**：立秋 r0=1.0 → r1=0.0，
    //   于是「霜降→立冬」是 15 天的连续过渡，正是我们要的（不硬跳）。
    r1: RANK.get(next),
  }];
}));

/**
 * 段内进度 t（0..1）与季内秩次（0..1）。
 *
 * ★ 为什么要把两个量分开返回（2026-10-04 修一个真实的语义错用）：
 *   第一版让 `termGain` 拿 `norm`（季内秩次）当"从本档插值到下一档的权重"，
 *   看起来能跑、也有输出，但**语义是错的** ——
 *   谷雨的秩次是 1.0（春季最后一档）、立夏是 0.0（夏季第一档），
 *   于是谷雨在 t=0 时就被算成了"离立夏已有 100% 进度" ⇒
 *   **谷雨直接输出了立夏的色**（实测抓到：两档 gain 完全相同 2.7082/0.9798/0.9675）。
 *   `norm` 的语义是"这一档在**本季内**排第几"，不是"离下一档还有多远"。
 *   `SEG` 里算出来的 `t` 才是后者。两者在季内恰好同值（因为秩次等距），
 *   **只在跨季那一档暴露** —— 跨季时 r0=1 → r1=0，混用立刻错。
 */
function seasonalWarmth(warmth, term) {
  return segProgress(warmth, term).norm;
}

function segProgress(warmth, term) {
  // 有节气名 ⇒ 走秩次，并在段内按 warmth 反解连续插值（见 SEG 的说明）。
  // 拿不到（如老存档只有档案没有 term）⇒ 退回季内 warmth 的线性归一化。
  const seg = term ? SEG.get(term) : null;
  if (seg) {
    const dw = seg.w1 - seg.w0;
    const t = Math.abs(dw) < 1e-6 ? 0 : clamp01((warmth - seg.w0) / dw);
    return { t, norm: clamp01(seg.r0 + (seg.r1 - seg.r0) * t) };
  }
  const s = seasonOf(warmth, term);
  const [lo, hi] = SEASON_WARMTH[s] || SEASON_WARMTH.spring;
  return { t: 0, norm: clamp01((warmth - lo) / Math.max(1e-6, hi - lo)) };
}

/**
 * 浮叶/落叶的数量上下限（片）。0 是"池面干净"，不是"没接"。
 *
 * ★★ LEAF_MAX 取 24 而不是 22 —— 因为 `Math.round` 会吃掉顶端的小数。
 *   `leaf=.98` × 22 = 21.56 → round = 22；`leaf=1` × 22 = 22 → 也是 22。
 *   两档**荷叶数完全相同** ⇒ 荷叶这条通道对它们零贡献。
 *   24 让 .98×24=23.5→24 与 1×24=24 仍然相同 —— 也不行。
 *   ⇒ 真正的解是**上限留一档余量**：LEAF_MAX=25 时 .98×25=24.5→25、1×25=25，还是相同。
 *   ⚠️ 结论：`round(leaf*MAX)` 在 leaf→1 时必然饱和，**靠 MAX 解决不了**。
 *   正解是让档案的 leaf 峰值也**不撞 1**（下面夏至改成 .96），
 *   这样 round(.96*22)=21 与 round(1*22)=22 才拉开 1 片。
 *   MAX 保持 22：它就是"盛夏满池"的物理上限，改大反而会让画面浮叶过密。
 */
const LEAF_MAX = 22;
const LITTER_MAX = 20;
/* ★★ 2026-10-04 新增：荷花的两个形态通道。
 * 需求表（开发提示词 101–111）把荷花画成一条**完整物候**：
 *   惊蛰·春分 新芽小花苞尖 → 清明·谷雨 花苞挺立 → 立夏·小满 初花开放
 *   → 芒种·夏至 荷花盛放 → 小暑·大暑 盛极花最繁 → 立秋·处暑 余花犹存
 *   → 白露·秋分 **花谢、莲蓬显现** → 寒露·霜降 **莲蓬枯梗** → 冬 残荷覆雪
 * 而改动前只有 `leaf`/`lotus` 两个数，**花苞与莲蓬这两种形态根本没地方表达**
 * —— 于是"花谢莲蓬显现"这一整行需求在画面上是空的（秋三档只有黄叶）。
 * BUD_MAX 取 9：谷雨 .85→8 个花苞，配合「春分七八支花苞待放」的参考图描述。
 * POD_MAX 取 5：秋分 .72→4 个莲蓬，是需求表标注的「设计图主态」。 */
const BUD_MAX = 9;
const POD_MAX = 5;

/**
 * 一个节气的渲染参数。
 *
 * @param profile `almanac.js` 的档案对象（`termProfile(t)` 或 `blendTerm(t, x)` 的返回值）
 */
export function TERM_VISUAL(profile, options) {
  // ⚠️ 拿不到档案时给**中性春**，不是 `{warmth:.5}` 这种"编出来的数"。
  //   中性春的好处是：老存档（无 `almanacProfile`）拿到的画面
  //   仍与改动前接近，而不是突然变成另一种风格。
  const p = profile && Number.isFinite(profile.warmth)
    ? profile
    : { warmth: 0.58, lotus: 0, leaf: 0.3, litter: 0.2, frost: 0, ice: 0 };

  const warmth = clamp01(p.warmth);
  const ice = clamp01(p.ice ?? 0);
  const frost = clamp01(p.frost ?? 0);
  const leaf = clamp01(p.leaf ?? 0);
  const litter = clamp01(p.litter ?? 0);
  const lotus = clamp01(p.lotus ?? 0);

  // ── 水色：两端插值 ────────────────────────────────────────────────
  // ★ 冷暖权重用 `warmth` 而不是 `1-ice`：立冬 ice 只有 .4 但已经"冷"了
  //   （warmth .28），单看 ice 会让秋末的水色还是暖的。
  //
  // ★★★ 2026-10-04：这里的定义域从 [COLD,WARM] 的**局部 lerp** 改成
  //   **按季节归一化后再映到全幅**。这是"档间差被吃掉"的第四例，与前三次同源：
  //     ① 荷叶 leaf→1 时 round() 饱和 ② 夏至 warmth=1 撞上界
  //     ③ 雪厚 0.35+0.65×deepWinter 撞上界 ④ **就是这里**
  //   实测（改动前）：春分 tint=(.723,.868,.713) vs 清明 (.728,.872,.708)
  //     ⇒ 档间差只有 **0.005~0.010**，再乘 amt(.33~.39) 与 water，
  //     最终画面差 0.4 灰阶、感知 ΔE 仅 **1.19**（阈值 5，差 4 倍）。
  //   根因：`warmth` 全域只有 .02~.99，而 `lerp` 的两端差 0.25 ⇒ 单档步长被
  //   除以 0.25，**同季相邻档（warmth 步长 0.04~0.13）只吃掉 16%~52%**，
  //   再经 TINT_BASE 二次压缩，几乎归零。
  //   正解：先在**本季内**把 warmth 归一化到 0..1，让六档**吃满 tint 全幅**，
  //   再映到 COLD->WARM 的全段。跨季靠 TINT_BASE 兜底（那里本来就该有强差异）。
  // 秩次优先（步长恒定）；拿不到节气名时退回线性归一化。
  // ⚠️ 用 solarTerm（引擎 options 里的字段），不是 almanacTerm（只在 UI settings 里）。
  //   读错字段的后果是静默的：termName=null ⇒ seasonOf 退回 warmth 阈值 ⇒ 又错 7 档。
  const termName = options?.solarTerm || null;
  /* ★★★ 水色 = 24 档实测查表，不再是两点 lerp（见 TERM_TINT_HSV 的说明）。
     * 段内（15 天）沿**段内进度 t** 在本档与日历下一档的实测值之间插值。
     * ⚠️ 必须用 `t` 不能用 `norm`：norm 是"季内秩次"，跨季那档
     *   （谷雨 r=1.0 → 立夏 r=0.0）会把它当插值权重用，直接输出下一档的颜色。
     *   详见 `segProgress` 的注释。
     */
  const seg = segProgress(warmth, termName);
  const norm = seg.norm;
  /* HSV 三元组 [dh(度), ks(饱和比), kv(亮度比)]。
     * ⚠️ dh 的插值**必须走短路径**：寒露(-124) 与霜降(-131) 是绕反方向近一周，
     *   若跨季插值从 -131 走到 -20（立冬）走的是"经过 0/360 分界"的路线，
     *   会在半路插出青/红色的错误色相。`lerpAngle` 负责这件事。 */
  const hsv = termHsv(termName, seg.t, warmth);
  /* 旧的 tint 三元组保留输出：它仍被 tests/probe-terms 与老存档路径消费。
     * 现在它由 HSV 参数**导出**（在 HSL 近似下反解），不再是独立的 lerp 权重 ——
     * 老存档（无 solarTerm）走 termHsv 的兜底分支时它才回到纯权重语义。 */
  const tintRgb = hsvToTint(hsv);
  const tint = {
    r: tintRgb[0], g: tintRgb[1], b: tintRgb[2],
  };

  // ── 焦散：档案 `warmth` × 现有 CAUSTIC 门控 ──────────────────────
  // ★ 不再只用 `CAUSTIC.season[termSeason]`（4 档），而是让 `warmth`
  //   连续调幅。这样谷雨(0.68) 与立夏(0.74) 的焦散量明显不同，
  //   而它们**同属 spring、共用同一张背景图** —— 差异只能来自这里。
  const seasonGain = CAUSTIC.season[seasonOf(warmth, options?.solarTerm)] ?? 1;
  const causticInk = CAUSTIC.ink * seasonGain * (0.12 + 0.88 * warmth * warmth);

  // ── 浮叶：叶 + 荷 ────────────────────────────────────────────────
  // 荷叶与浮叶绑在一起（荷叶本来就是"大号浮叶"），
  // `lotus` 只额外决定**是否开花**。这样谷雨有浮叶无荷花、小满有花，
  // 而不会出现"有荷花但没有叶子"。
  const leafCount = Math.round(leaf * LEAF_MAX);
  const lotusCount = Math.round(lotus * 5);
  // 花苞 / 莲蓬：荷花物候的另外两种形态（见 BUD_MAX 上方的需求表对照）。
  // ⚠️ 这两个数是**独立于 lotusCount** 的，不能从它推导 ——
  //   "谷雨 8 苞 0 花" 与 "白露 0 苞 0 花但有 4 莲蓬" 在 lotusCount 上都是 0，
  //   靠 lotus 推不出来，而它们在画面上必须完全不同。
  const budCount = Math.round(clamp01(p.bud ?? 0) * BUD_MAX);
  const podCount = Math.round(clamp01(p.pod ?? 0) * POD_MAX);

  /* ═══ 2026-10-05 荷花「开花过程」：从 bud → 盛放之间的连续量 ═══
   *
   * ★ 用户反馈「荷花缺少开花的过程」—— 改前只有两档：
   *   `budCount` 个**紧闭花苞** + `lotusCount` 朵**全开荷花**，
   *   中间是**跳变**的（谷雨 8 苞 0 花 → 立夏 19 叶 2 花，中间没有"正在开"）。
   *
   * ★★ 为什么**派生**而不是给档案加 `bloom` 字段：
   *   ① `lotus` 已经是**连续物候量**且有需求表背书（开发提示词 101–111
   *      逐档写了「初花开放 → 荷花盛放 → 盛极花最繁 → 余花犹存 → 花谢」）。
   *      再加一个通道，两者会**互相打架**：某档该听 bloom 的还是 lotus 的？
   *   ② 加字段要改 24 档档案 + 插值（`blendTerm`）+ 中性档案 + 单测，
   *      改动面大且新通道没人验证过。
   *   ③ 派生量**不可能与 lotus 不一致**（同一个数算出来的）。
   *   ⇒ 所以：`openness` = 「一朵花从紧闭到全开的进度」，0=紧闭、1=全开，
   *     由 lotus 归一而来；`openCount` = 处于「半开以上」的花朵数。
   *
   * 映射的三个关键点（都是量出来的，不是拍的）：
   *   · **零点不是 0**：谷雨 lotus=.10 要求「花苞挺立、尖尖立着」，
   *     而立夏 .30 才是「初花开放」。所以窗口从 .06 起，而不是从 0 起。
   *   · ★★ **分母必须覆盖档案峰值 .94，否则四档撞顶同形**（实测踩过）：
   *     第一版窗口写成 `.06 / .56` ⇒ 芒种 .78、大暑 .62、夏至 1.00、小暑 .82
   *     **四档的 raw 全是 1.000** ⇒「盛极花最繁」与「余花犹存」在画面上
   *     毫无区别 —— 与 LEAF_MAX 撞顶是同一类饱和，靠调系数解决不了。
   *     正解 = **窗口上沿取到档案峰值**（分母 .94 ⇒ lotus=1 恰好得 1.0，
   *     而 .78→.766、.82→.809、.62→.596 全部拉开）。
   *     ⚠️ 唯一允许饱和的是夏至 1.00 —— 它本就是峰值，需求也只要求「荷花盛放」，
   *     再往上没有档位。
   *   · **rawOpenness 才是真正送进渲染层的量** ——
   *     `openness`（截断到 0..1）只用来判"这朵算不算开"，
   *     瓣张开的角度用 `rawOpenness`（不截断，可 > 1 ⇒ 极盛时更张）。
   *     ★★★ 这就是记忆里那条「判据量必须选真正送进 shader/渲染的那个量」的同型坑。
   */
  const rawOpenness = clamp01((lotus - 0.06) / 0.94);
  const openness = clamp01(rawOpenness);
  /* 处于「半开以上」的花朵数。
   * ⚠️ 系数 2.2 的来历：立夏 lotus=.30 → raw=.255（×2.2=.56 ⇒ 2 朵里 1 朵开），
   *   而谷雨 .10 → raw=.043（×2.2=.095 ⇒ 1 朵都不开）。
   *   这样「立夏初开、谷雨纯苞」在同一公式下成立，且白露 .08→.021 稳在紧闭侧。 */
  const openCount = lotusCount > 0 ? Math.max(1, Math.round(lotusCount * Math.min(1, rawOpenness * 2.2))) : 0;

  // ── 落叶 ──────────────────────────────────────────────────────────
  const litterCount = Math.round(litter * LITTER_MAX);

  /* ── 雨势（2026-10-07，P2-2「雨水不下雨」）─────────────────────────
   * 档案新增的 `rain` 维直通这里，**不做二次推导** ——
   *   它已经是物候量（雨水 1 / 惊蛰 .35 / 立春 .25），再推导就等于
   *   把「哪一档该下雨」的决定权从档案挪到一条公式上，
   *   而档案才是可核对、可评审的第二信源。
   * ⚠️ 必须 `?? 0`：老存档 / 中性档案没有这个键时回退到「无雨」，
   *   而不是 `undefined` 漏进渲染层。 */
  const rain = clamp01(p.rain ?? 0);

  // ── 冰：只剩**霜纹**（2026-10-07，冰层与泉眼都已取消）────────────────
  // `frost` 走"岸边/水面浮霜"（薄、局部）。`ice` 现在**只驱动降雪强度**
  //   （`pond.js` 的 `drawWeather`：`Math.round(14+18*ice)`），
  //   不再有任何"封住水面"的绘制 —— 所以 `ice` 这个名字有误导性，
  //   但**不能删**：删了冬六档的雪片数就没有连续档位了
  //   （`ice` 在大雪/冬至/小寒/大寒全是 1，从它推雪量会让四档完全一样）。
  //
  // ★★ `iceHole`（活水泉眼半径）与 `steam`（蒸汽强度）**已整体删除**。
  //   用户要求「删除冬天结冰和留着洞冒泡的设计」。
  //   ⚠️ 必须**连推导一起去删**，不能只删渲染层的消费者 ——
  //   留着就是「上游算了、下游没人读」的死通道，
  //   而那正是 `snow`/`cracks` 当年踩过的坑（算了半年一次没画）。
  //   ⇒ `deepWinter` 仍然保留：它是**档案里的离散事实序号**（三九/四九），
  //     档案层不动（存档与24 档物候表都读它）。
  const deep0 = clamp01(p.deepWinter ?? 0);

  // ── 冬季六档的冰形态 ─────────────────────────────────────────────
  // ★ 为什么需要它们：用户反馈「每个节气之间都一样」。
  //   冬六档（大雪/冬至/小寒/大寒）**全部 ice=1、frost=1、leaf=0、lotus=0、
  //   焦散全被压到 .006** ⇒ 在画面上几乎逐像素相同。
  //
  //   ★★ 这里踩过一个坑，值得完整记下来：**从 `warmth` 反推是错的**。
  //   第一版写 `w = (0.5 - warmth)/0.44` 想表达"越冷冰越厚"，
  //   结果小寒(.05) 与大寒(.02) 都超过上界被夹到 1.0
  //   ⇒ `snow` 全是 1.0、`cracks` 全是同一个值，**两档完全相同**。
  //   接着把 sin 曲线改成分段让末端分岔，也只把探针距离从 0.3 推到 0.3。
  //
  //   病根是**用连续量表达离散事实**：
  //     · "多冷" 是连续的（`warmth`）→ 适合做水色、焦散
  //     · "第几个九" 是离散的（序数，不是温度）→ 适合做冰的形态
  //   拿 `warmth` 去推后者，要么饱和、要么被压平在曲线端点。
  //   正解：档案直接给序号（`deepWinter`），这里只做一次线性映射。
  const deep = deep0;
  // 积雪：三九最厚，四九略收（雪压不住冰面，开始往边缘堆）
  const snow = deep <= 0.9 ? deep * 1.02 : 0.918 - (deep - 0.9) * 0.22;
  /* ★★ `cracks`（裂纹）**已整体删除**（2026-10-07，随冰下泉眼一起）。
   *   它原本唯一的消费者是泉眼边缘那圈「薄霜圈」
   *   （`pond.js` 的 `drawIceHole`：`rgba(238,251,246,${0.30+0.34*v.cracks})`）。
   *   泉眼删掉后它**一个消费者都不剩** ⇒ 必须连推导一起删，
   *   否则又变成「上游算了、下游没人读」的死通道。
   *   ⚠️ 别把它当成「顺手还能用」：裂纹属于**冰层**语义，
   *     而冰层已于 2026-10-05 取消 —— 留着裂纹通道就是留着冰的残骸。
   *   ⇒ `deepWinter` 仍导出（`snow` 与它同源，且档案层不动）。 */

  return {
    warmth,
    season: seasonOf(warmth, termName),   // ★ 补出：岸边花木要用它选当季物候
    deepWinter: deep0,          // ★ 补出：积雪压枝的厚度（原本只是内部中间量）
    tintR: tint.r, tintG: tint.g, tintB: tint.b,
    /* ★★★ HSV 变换参数（2026-10-04 换掉 RGB 乘色的原因见 TERM_TINT_HSV）。
     *   landscape.js 见此字段就走 HSV 路径：
     *     dh = 色相旋转（度，环形） ks = 饱和压缩比 kv = 亮度缩放比
     *   缺省为 null 时旧路径（BASE + tint*(1-BASE) 乘色）逐位不变。 */
    termTintHSV: hsv,
    causticInk,
    leafCount,
    lotusCount,
    budCount,
    podCount,
    /* 2026-10-05 开花过程（派生量，理由见上面那段注释） */
    openness,
    rawOpenness,
    openCount,
    litterCount,
    frost,
    ice,
    snow,
    // 供探针与调试用
    lotus,
    rain,
  };
}

/**
 * 季节判定 —— **优先查 TERM_SEASON 真源表**，拿不到才按 warmth 阈值兜底。
 *
 * ★★★ 2026-10-04 修掉一个**一直存在但从未被发现**的老 bug。
 *   旧实现是纯阈值反推（warmth ≥.72 夏 / ≥.52 春 / ≥.34 秋 / 其余冬），
 *   实测与 `almanac.js` 的 TERM_SEASON **7/24 档不一致**：
 *     立秋 .82→summer  处暑 .76→summer   （明明是秋，画成了夏）
 *     白露 .66→spring  秋分 .58→spring   （明明是秋，画成了春）
 *     立春 .30→winter  雨水 .40→autumn  惊蛰 .50→autumn（明明是春，画成了冬/秋）
 *   为什么一直没被发现：它在下游只影响 `CAUSTIC.season[season]` 这个**焦散倍率**，
 *   偏差只有 ±20~30% 的强度，**画面依然"正常渲染"，只是秋天的焦散偏强、
 *   春天的偏弱** —— 没有任何报错，也没有任何量具报警。
 *   本次做 tint 秩次时被 tint 放大成"立冬是黄绿色"才暴露。
 *
 *   ⚠️ 教训：**当一个派生量被下游放大时，它的小偏差会变成大问题**。
 *     所以派生量必须与真源对齐，而不是自己编一套阈值。
 */
export function seasonOf(warmth, term) {
  if (term) {
    const i = SOLAR_TERMS.indexOf(term);
    if (i >= 0 && TERM_SEASON[i]) return TERM_SEASON[i];
  }
  if (warmth >= 0.72) return 'summer';
  if (warmth >= 0.52) return 'spring';
  if (warmth >= 0.34) return 'autumn';
  return 'winter';
}

/**
 * 取当前档的 HSV 变换参数 [dh(度), ks(饱和比), kv(亮度比)]；
 * 段内沿**段内进度 t** 在本档与日历下一档的实测值之间插值。
 *
 * ★ 为什么不能用"季节基色 + 秩次 lerp"（旧做法）：
 *   那个式子的输出只由 (season, 季内序号) 决定，所以春分/夏至/冬至
 *   （季内序号都是第 4 档）必然算出同一个值。实测已确认三者旧输出完全相同。
 *   查表 + 相邻档插值没有这个自由度：每一档的色相都来自它自己的那一次实测。
 *
 * ⚠️ `dh` 走 `lerpAngle`（短路径）而不是 `lerp`：色相是**环形量**。
 *   359° → 1° 应该只走 +2°，而不是 lerp 的 -358°。
 *   不折到短路径，段内插值会在半路插出完全错误的颜色（青绿插成红）。
 *   `ks`/`kv` 用普通 lerp：它们是正实数比值，没有环形性。
 */
function termHsv(term, t, warmth) {
  const here = term ? TERM_TINT_BY_NAME.get(term) : null;
  if (!here) {
    // 拿不到节气名（老存档）⇒ 退回季内线性插值，至少仍是"一个季节一个色系"。
    const s = seasonOf(warmth, null);
    const list = TERM_RANK[s] || TERM_RANK.spring;
    const x = clamp01(t) * (list.length - 1);
    const i = Math.min(list.length - 2, Math.floor(x));
    const a = TERM_TINT_BY_NAME.get(list[i]), b = TERM_TINT_BY_NAME.get(list[i + 1]);
    const f = x - i;
    return [
      lerpAngle(a[0], b[0], f),
      lerp(a[1], b[1], f),
      lerp(a[2], b[2], f),
    ];
  }
  const idx = SOLAR_TERMS.indexOf(term);
  const nextTermName = SOLAR_TERMS[(idx + 1) % SOLAR_TERMS.length];
  const to = TERM_TINT_BY_NAME.get(nextTermName);
  if (!to) return [here[0], here[1], here[2]];
  return [
    lerpAngle(here[0], to[0], t),
    lerp(here[1], to[1], t),
    lerp(here[2], to[2], t),
  ];
}

/**
 * 环形插值：走**短路径**（|Δ| ≤ 180°）。
 * ★ 色相 359° → 1° 只走 +2°，而不是 lerp 的 -358°（那会插出中间的绿/黄）。
 */
function lerpAngle(a, b, t) {
  const d = ((((b - a) + 180) % 360) + 360) % 360 - 180;
  return a + d * t;
}

/* ★ 底图池心的基准 HSV（实测自 public/assets/winter.png的池心区），
 *   只用于把 HSV 参数**近似**导出成旧的 tintR/G/B 三元组。 */
const BASE_POOL_HSV = { h: 174.07, s: 0.6469, v: 168.42 / 255 };

function hsvToRgb255(h, s, v) {
  const c = v * s;
  const hp = ((((h % 360) + 360) % 360) / 60) % 6;
  const x = c * (1 - Math.abs((hp % 2) - 1));
  const m = v - c;
  const tbl = [
    [c, x, 0], [x, c, 0], [0, c, x],
    [0, x, c], [x, 0, c], [c, 0, x],
  ][Math.floor(hp)] || [0, 0, 0];
  return [(tbl[0] + m) * 255, (tbl[1] + m) * 255, (tbl[2] + m) * 255];
}

/**
 * 由 HSV 参数**近似**导出旧的 `tintR/G/B`。
 *
 * ★ 为什么保留这三个字段：它们被 `tools/probe-terms.mjs`（总表打印 + 冷暖轴判据）
 *   与 `tools/shot-terms-ui.cjs` 消费。删掉要同时改三个工具，
 *   而那些工具本身没坏——只是这三个字段的语义从"归一化色度权重"
 *   变成了"HSV 的近似读数"。
 *
 * ⚠️ 这是**近似**，不是精确导出：真实渲染是**逐像素**按各自 H/S/V 变换的，
 *   池心读数只是其中一个特例。⇒ 探针里凡依赖**绝对精度**的判据
 *   都不该再用 tintR/G/B；要判池心实际色请走离屏渲染（`check-term-delta.cjs`）。
 *   这条正是「像素级量具的 11 次失效」里第1 次的同款：
 *   读引擎参数 ≠ 读画面。
 */
function hsvToTint(hsv) {
  return hsvToRgb255(
    BASE_POOL_HSV.h + hsv[0],
    clamp01(BASE_POOL_HSV.s * hsv[1]),
    clamp01(BASE_POOL_HSV.v * hsv[2]),
  );
}

const clamp01 = (v) => (Number.isFinite(v) ? Math.max(0, Math.min(1, v)) : 0);
const lerp = (a, b, t) => a + (b - a) * t;

