  senseFraction: 0.25,
  /**
   * 聚合死区 = 视口短边 × 该系数。比这更近就不拉了 —— 交给分离力。
   * ⚠️ 没有死区的话鱼会**贴成一坨**：分离力在 personalSpace 外就为 0，
   *    而聚合拉力一直存在，稳定点是"互相压住"，画面会读成一条鱼。
   */
  deadZoneFraction: 0.055,
  /**
   * 聚合拉力的**径向形状**（`'hill'` | `'linear'`）。
   *
   * ★ 为什么不能只有「距离越近拉得越狠」这一种形状：
   *   初版是 `pull = 1 − r / sense` —— 在 `r = 0` 处最强，**单调递减**。
   *   把死区一起看：`r = dead` 处的拉力 = `1 − dead / sense`，
   *   代入 0.055 / 0.17 ⇒ **0.68**，也就是说死区边界上的拉力仍有满值的 68%。
   *   ⇒ 「比这更近就不拉了」的**死区形同虚设**，稳定点被推到"能多近就多近"。
   *   实测症状：公平对照对参数极不敏感（改 sense 从 0.17 到 0.60 几乎不动），
   *   因为不论怎么改，边缘处的拉力都还是接近满值 —— 拉力始终是"吸到叠住为止"。
   *
   *   `hill` 形状 `pull = sin(π·(r − dead) / (sense − dead))`：
   *   在 `r = dead` 与 `r = sense` **两端都归零**，中点最强。
   *   这才读得出「太近不拉（有分离力在推）、适中才拉、太远看不见」的区间感，
   *   也才有**唯一**的稳定间距而不是"一直吸到撞上"。
   *
   * ⚠️ 保留 `linear` 只是为了 A/B 对照（`tools/probe-school.js --hill=linear`），
   *    生产路径用 `hill`。
   */
  pullShape: 'hill',
  /** 额外的分离半径倍率：[阶段 key, 倍率]（§6 亚成体「领域意识」/ 老鱼「离群独处」）
   *
   * ★ 这个倍率是**成对取双方较大者**之后再乘的（见 simulation.js 的邻居循环），
   *   所以它是「这条鱼和对方之间要保持几个身位」，不是「这条鱼单方面后退多少」。
   *
   * ★ 为什么老鱼要 4.0 这么大：
   *   初版给 1.55，实测**完全没有隔离效果** —— 「老鱼到最近一尾鱼的距离 ÷ 全池中位」
   *   恒为 **1.00**（4 个种子、每个 600+ 样本）。根因是分离力在 `personalSpace` 之外
   *   就为 0，而 1.55 倍下两尾老鱼的个人空间只有 `0.29×(108+108)×1.55 ≈ 97px`，
   *   出了这 97px 就没人管它们了，浪游目标把两尾老鱼又凑到一起。
   *   4.0 倍 ⇒ 老鱼之间 250px、老鱼与鱼苗之间 130px ⇒ 隔离度实测 **1.39–1.82**（跨 2 个种子）。
   *   代价核对：老鱼「贴到画幅边缘 13% 带里」的时间占比 **0%**（没有把老鱼挤到墙角）。
   */
  spaceScale: [['subadult', 1.35], ['elder', 4.0]],
